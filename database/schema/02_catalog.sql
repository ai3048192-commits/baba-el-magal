-- =====================================================================
-- 2) الأقسام والمنتجات  ← categories.js / products.js
-- =====================================================================
create table if not exists public.categories (
  id          text primary key,                -- kitchen  →  /category/kitchen
  name        text not null,
  icon        text not null default 'Box',
  sort_order  int  not null default 0
);

create table if not exists public.subcategories (
  id           bigint generated by default as identity primary key,
  category_id  text not null references public.categories(id) on delete cascade,
  name         text not null,
  sort_order   int  not null default 0,
  unique (category_id, name)
);

create table if not exists public.products (
  id             bigint generated by default as identity primary key,
  sku            text unique,                  -- كود المنتج في المخزن (للربط بالـ ERP)
  external_id    text,                         -- رقم المنتج في نظام المخزن الخارجي
  name           text not null,
  description    text default '',
  price          numeric(10,2) not null check (price >= 0),
  old_price      numeric(10,2) not null default 0,
  rating         numeric(2,1) not null default 4.5,
  reviews_count  int not null default 0,
  category_id    text not null references public.categories(id),
  subcategory    text,
  image          text not null,
  images         text[] not null default '{}',
  badge          text default '',
  tag            text default '',
  stock          int not null default 0 check (stock >= 0),
  total_stock    int not null default 0,
  features       text[] not null default '{}',
  specs          jsonb not null default '[]',  -- [{label, value}]
  colors         jsonb not null default '[]',  -- [{name, code}]
  sections       text[] not null default '{catalog}', -- catalog / featured / discounts / bestseller
  active         boolean not null default true,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index if not exists idx_products_category on public.products(category_id);
create index if not exists idx_products_sections on public.products using gin(sections);

create table if not exists public.reviews (
  id          bigint generated by default as identity primary key,
  product_id  bigint not null references public.products(id) on delete cascade,
  name        text not null check (length(name) between 2 and 80),
  city        text default '',
  comment     text not null check (length(comment) between 3 and 1000),
  rating      smallint not null check (rating between 1 and 5),
  approved    boolean not null default true,     -- خليها false لو عايز تراجع قبل النشر
  created_at  timestamptz not null default now()
);
create index if not exists idx_reviews_product on public.reviews(product_id);
