create table if not exists public.offers (
  id                bigint generated by default as identity primary key,
  title             text not null,
  subtitle          text default '',
  kind              text not null check (kind in ('daily','weekly','range')),
  weekdays          int[] not null default '{}',   -- 0 الأحد … 5 الجمعة، 6 السبت
  start_date        date,
  end_date          date,
  product_ids       bigint[] not null default '{}',
  discount_percent  numeric(5,2) not null default 0 check (discount_percent between 0 and 90),
  badge             text default '',
  show_on_home      boolean not null default true,
  active            boolean not null default true,
  created_at        timestamptz not null default now()
);

create table if not exists public.coupons (
  id      bigint generated by default as identity primary key,
  code    text not null unique,
  type    text not null check (type in ('percent','fixed','shipping')),
  value   numeric(10,2) not null default 0,
  active  boolean not null default true
);

create table if not exists public.wheel_prizes (
  id          bigint generated by default as identity primary key,
  label       text not null,
  code        text default '',
  color       text not null default '#E50914',
  sort_order  int default 0
);
