create table if not exists public.orders (
  id                   bigint generated by default as identity primary key,
  number               text not null unique,                -- BEM-123456
  status               text not null default 'new'
                         check (status in ('new','confirmed','processing','shipped','out_for_delivery','delivered','cancelled','returned')),
  customer_name        text not null,
  phone                text not null,
  phone2               text,
  governorate          text not null,
  city                 text not null,
  address              text not null,
  landmark             text,
  preferred_time       text,
  notes                text,
  payment_method       text not null check (payment_method in ('cod','card','wallet','fawry')),
  wallet_phone         text,
  wallet_ref           text,
  fawry_code           text,
  coupon_code          text,
  subtotal             numeric(10,2) not null,
  discount             numeric(10,2) not null default 0,
  shipping             numeric(10,2) not null default 0,
  total                numeric(10,2) not null,
  deposit_amount       numeric(10,2) not null default 0,    -- العربون
  deposit_paid         boolean not null default false,
  deposit_phone        text,
  deposit_ref          text,
  shipping_company_id  bigint references public.shipping_companies(id) on delete set null,
  tracking_number      text,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now()
);
create index if not exists idx_orders_status on public.orders(status);
create index if not exists idx_orders_phone  on public.orders(phone);

create table if not exists public.order_items (
  id          bigint generated by default as identity primary key,
  order_id    bigint not null references public.orders(id) on delete cascade,
  product_id  bigint references public.products(id) on delete set null,
  name        text not null,          -- نسخة وقت الشراء
  image       text,
  price       numeric(10,2) not null, -- نسخة وقت الشراء
  qty         int not null check (qty > 0),
  color       text
);
create index if not exists idx_order_items_order on public.order_items(order_id);

-- سجل التتبع: كل تغيير في الحالة أو ملاحظة بتظهر للعميل في /track
create table if not exists public.order_events (
  id          bigint generated by default as identity primary key,
  order_id    bigint not null references public.orders(id) on delete cascade,
  status      text not null,
  note        text,
  source      text not null default 'admin',   -- admin / customer / webhook
  created_by  uuid default auth.uid(),
  created_at  timestamptz not null default now()
);
create index if not exists idx_order_events_order on public.order_events(order_id);
