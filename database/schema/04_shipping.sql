create table if not exists public.shipping_companies (
  id              bigint generated by default as identity primary key,
  name            text not null,
  provider        text not null default 'manual', -- manual / bosta / aramex / mylerz / jt / r2s / custom
  logo            text default '',
  phone           text default '',
  tracking_url    text default '',                -- {tracking} بيتبدل برقم البوليصة
  estimated_days  text default '',
  cod_supported   boolean not null default true,
  active          boolean not null default true,
  created_at      timestamptz not null default now()
);

-- بيانات الـ API لكل شركة — سرية، الأدمن والـ Edge Functions بس
create table if not exists public.shipping_company_credentials (
  company_id          bigint primary key references public.shipping_companies(id) on delete cascade,
  enabled             boolean not null default false,
  base_url            text default '',
  api_key             text default '',
  api_secret          text default '',
  account_id          text default '',
  pickup_location_id  text default '',
  updated_at          timestamptz not null default now()
);

create table if not exists public.shipping_zones (
  id           bigint generated by default as identity primary key,
  governorate  text not null unique,
  fee          numeric(10,2) not null default 0,
  days         text default ''
);
